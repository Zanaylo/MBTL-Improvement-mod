bool PartColourTable::IsPartEntry(int chara, int entry)
{
	return GetPartCount(chara, entry) > 0;
}

int PartColourTable::GetPartCount(int chara, int entry)
{
	const Chara* const found = FindChara(chara);

	if (found == nullptr)
		return 0;

	for (int i = 0; i < found->count; ++i)
	{
		if (found->rows[i].entry == entry)
			return found->rows[i].parts;
	}

	return 0;
}

bool PartColourTable::BuildAutoEffectBlock(int chara, const uint8_t* colours, uint8_t* outEffect)
{
	const Chara* const found = FindChara(chara);

	if (found == nullptr || colours == nullptr || outEffect == nullptr)
		return false;

	for (int i = 0; i < found->count; ++i)
	{
		const int entry = found->rows[i].entry;

		outEffect[entry * 4 + 0] = colours[entry * 4 + 0];
		outEffect[entry * 4 + 1] = colours[entry * 4 + 1];
		outEffect[entry * 4 + 2] = colours[entry * 4 + 2];
		outEffect[entry * 4 + 3] = 255;
	}

	return found->count > 0;
}
